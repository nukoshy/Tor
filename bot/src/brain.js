// WhatsApp не понимает markdown: **жирный** → *жирный*, заголовки и __курсив__ приводим к виду WhatsApp.
// Плюс вычищаем служебную пометку «[менеджер]:» — она из истории диалога и клиенту уходить не должна.
function sanitizeWhatsApp(t) {
  return t
    .replace(/\*\*(.+?)\*\*/gs, "*$1*")
    .replace(/__(.+?)__/gs, "_$1_")
    .replace(/^#{1,6}\s+/gm, "")
    .replace(/\[менеджер\]:\s*/gi, "")
    .trim();
}

// Сводка занятости без утечки чужих имён: события группируются по названию зала в summary.
function summarizeAvailability(events) {
  const n = { kabinka: 0, neke_sarayi: 0, banket_zal: 0, karaoke: 0, other: 0 };
  for (const e of events) {
    const s = (e.summary || "").toLowerCase();
    if (s.includes("кабинк")) n.kabinka++;
    else if (s.includes("неке")) n.neke_sarayi++;
    else if (s.includes("банкет")) n.banket_zal++;
    else if (s.includes("караоке")) n.karaoke++;
    else n.other++;
  }
  const out = {
    kabinka: n.kabinka >= 2 ? "заняты обе" : n.kabinka === 1 ? "свободна 1 из 2" : "свободны обе",
    neke_sarayi: n.neke_sarayi ? "занят" : "свободен",
    banket_zal: n.banket_zal ? "занят" : "свободен",
  };
  if (n.karaoke) out.karaoke = `${n.karaoke} записи — слоты подтверждает менеджер`;
  if (n.other) out.warning = `на дату есть ${n.other} событие(й) без зала в названии — предупреди, что менеджер перепроверит`;
  return out;
}

function daysFromToday(dateISO) {
  const t = Date.parse(todayISO());
  const d = Date.parse(dateISO);
  if (Number.isNaN(d)) return null;
  return Math.round((d - t) / 86400000);
}

async function runTool(tc, chatId, deps) {
  const args = JSON.parse(tc.function.arguments || "{}");
  const phone = chatId.replace(/@.*$/, "");
  // @lid — скрытый идентификатор WhatsApp, это не номер телефона
  const contact = chatId.endsWith("@lid") ? `WhatsApp-чат ${phone} (скрытый номер)` : `+${phone}`;
  const name = tc.function.name;

  if (name === "check_availability" || name === "create_hold") {
    const diff = daysFromToday(args.date || "");
    if (diff === null) return { error: "bad_date", note: "Дата не распознана, уточни у клиента." };
    if (diff < 0) return { error: "date_in_past", note: "Эта дата уже прошла — уточни у клиента." };
    if (diff > cfg.maxAdvanceDays)
      return { error: "date_too_far", note: `Бронь дальше ${cfg.maxAdvanceDays} дней оформляет только менеджер — предложи notify_manager.` };
  }

  if (name === "check_availability") {
    if (!calendar.configured())
      return { status: "unknown", note: "Календарь не подключён. Скажи клиенту, что занятость уточнит менеджер при подтверждении, и оформляй заявку дальше." };
    const events = await calendar.eventsOn(args.date);
    return {
      date: args.date,
      availability: summarizeAvailability(events),
      note: "Сообщай клиенту только свободно/занято — имена и детали чужих броней не раскрывай.",
    };
  }

  if (name === "create_hold") {
    if (!/^([01]?\d|2[0-3]):[0-5]\d$/.test(args.time_start || "")) delete args.time_start; // кривое время → 16:00
    const hold = { ...args, phone };
    let saved = false;
    if (calendar.configured()) {
      await calendar.createHold(hold);
      saved = true;
    }
    await deps.alert(
      [
        `🆕 Заявка из бота${saved ? " (записана в календарь)" : " (календарь не подключён!)"}`,
        `${calendar.hallName(args.hall)} · ${args.date} · с ${args.time_start || "16:00"}`,
        `${args.client_name}, ${args.guests} гостей, ${args.event_type || "событие"}${
          args.package && args.package !== "не выбран" ? `, пакет ${args.package} ₸` : ""
        }`,
        `WhatsApp клиента: ${contact}`,
        args.comment ? `Комментарий: ${args.comment}` : "",
      ]
        .filter(Boolean)
        .join("\n")
    );
    return {
      ok: true,
      saved_to_calendar: saved,
      note: "Скажи клиенту: заявка принята, менеджер свяжется и подтвердит бронь. Ничего окончательно не подтверждай сам.",
    };
  }

  if (name === "notify_manager") {
    await deps.alert(`❗️ Нужен менеджер\n${args.summary}\nWhatsApp клиента: ${contact}`);
    return { ok: true, note: "Скажи клиенту, что передал вопрос менеджеру — ответят в ближайшее время." };
  }

  return { error: "unknown_tool" };
}

// Язык последнего сообщения клиента — кодом, чтобы модель не «уплывала» за историей диалога
function detectLang(text) {
  const t = (text || "").toLowerCase();
  if (/[әіңғүұқөһ]/.test(t)) return "kk";
  if (/с[аә]леметс|ассалау|салам|қайырлы|рахмет|бар ма|келед[иі]|болад[ыі]|адам|қанша|мәзір/.test(t)) return "kk";
  if (/[а-яё]/.test(t)) return "ru";
  // Транслит латиницей: казахские и русские маркеры
  if (/salem|assalau|assalam|qansha|kansha|turad[yi]|jasaim|zhasaim|\btoi\b|\bbar ma\b|adamby[sz]|kuni\b/.test(t)) return "kk";
  if (/uzatu|tusau|besik|kerek\b|keshke|\bqalai\b|\bkalai\b|zhazyl|jazyl|keled[iy]|adamg[ae]|qona[qk]|konak\b|ra[kh]?hmet/.test(t)) return "kk";
  if (/zdravstv|zdrast|privet\b|skolko|stoit\b|mozhno|zabronir|svobodn|pozhalu[jy]sta/.test(t)) return "ru";
  if (/chelovek|zavtra\b|vecher|\bdobr[yi]|segodnya|sevodnya/.test(t)) return "ru";
  return null;
}

// history: [{role: "user"|"assistant", content}], deps: { alert(text) }
async function respond(chatId, history, deps) {
  const messages = [
    { role: "system", content: systemPrompt() },
    ...history.map((h) => ({ role: h.role === "user" ? "user" : "assistant", content: h.content })),
  ];
  const lastUser = [...history].reverse().find((h) => h.role === "user");
  const lang = detectLang(lastUser?.content);
  if (lang) {
    messages.push({
      role: "system",
      content: `Последнее сообщение клиента написано на ${lang === "kk" ? "казахском" : "русском"} языке — ответь строго на нём, даже если раньше диалог шёл на другом.`,
    });
  }
  let langRetried = false;
  for (let i = 0; i < 5; i++) {
    const out = await chatComplete({ messages, tools: TOOLS });
    if (!out.toolCalls.length) {
      const text = sanitizeWhatsApp((out.content || "").trim());
      // Страховка кодом: ответ не на языке клиента → один принудительный перевод
      if (lang && !langRetried && out.raw) {
        const hasKk = /[әіңғүұқөһ]/.test(text);
        const wrongLang = (lang === "ru" && hasKk) || (lang === "kk" && !hasKk && /[а-яё]/i.test(text));
        if (wrongLang) {
          langRetried = true;
          messages.push(out.raw);
          messages.push({
            role: "system",
            content: `Ты ответил не на том языке: клиент писал на ${lang === "kk" ? "казахском" : "русском"}. Переведи свой ответ на ${lang === "kk" ? "казахский" : "русский"} и отправь только перевод, без пояснений.`,
          });
          continue;
        }
      }
      return text;
    }
    messages.push(out.raw);
    for (const tc of out.toolCalls) {
      let result;
      try {
        result = await runTool(tc, chatId, deps);
      } catch (e) {
        console.error(`tool ${tc.function?.name} failed:`, e.message);
        result = { error: String(e.message || e) };
      }
      messages.push({ role: "tool", tool_call_id: tc.id, content: JSON.stringify(result) });
    }
  }
  return "Секунду, уточню у менеджера и вернусь к вам 🙌";
}

